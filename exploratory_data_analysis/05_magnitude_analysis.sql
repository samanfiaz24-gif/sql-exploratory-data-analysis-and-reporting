/*
=============================================================================
Dimensional Aggregation Analysis
=============================================================================
Purpose:
    Analyze the magnitude and distribution of business measures across
    customer, product, and geographic dimensions.

Analysis:
    1. Examine customer distribution by country and gender.
    2. Analyze product distribution and average costs.
    3. Evaluate revenue contributions by category and customer.
    4. Assess sales quantities and performance across countries.
=============================================================================
*/

-- =============================================================================
-- 1. Customer Distribution Analysis
-- =============================================================================

-- Calculate the number of customers in each country.
SELECT
    country,
    COUNT(DISTINCT customer_id) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-- Calculate the number of customers by gender.
SELECT
    gender,
    COUNT(DISTINCT customer_id) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;


-- =============================================================================
-- 2. Product Distribution Analysis
-- =============================================================================

-- Count distinct products within each category.
SELECT
    category,
    COUNT(DISTINCT product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

-- Calculate the average product cost by category.
SELECT
    category,
    ROUND(AVG(cost), 2) AS avg_cost
FROM gold.dim_products
GROUP BY category
ORDER BY avg_cost DESC;


-- =============================================================================
-- 3. Revenue Distribution Analysis
-- =============================================================================

-- Calculate total revenue generated by each product category.
SELECT
    p.category,
    SUM(s.sales_amount) AS total_revenue
FROM gold.fact_sales AS s
LEFT JOIN gold.dim_products AS p
    ON s.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Calculate total revenue generated by each customer.
SELECT
    c.customer_key,
    c.firstname,
    c.lastname,
    SUM(s.sales_amount) AS total_revenue
FROM gold.fact_sales AS s
LEFT JOIN gold.dim_customers AS c
    ON s.customer_key = c.customer_key
GROUP BY
    c.customer_key,
    c.firstname,
    c.lastname
ORDER BY total_revenue DESC;


-- =============================================================================
-- 4. Geographic Sales Distribution
-- =============================================================================

-- Examine the distribution of sold quantities across countries.
SELECT
    c.country,
    SUM(s.quantity) AS total_sold_items
FROM gold.fact_sales AS s
LEFT JOIN gold.dim_customers AS c
    ON s.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC;


-- =============================================================================
-- 5. Product Classification Analysis
-- =============================================================================

-- Count products within each product line.
SELECT
    product_line,
    COUNT(DISTINCT product_key) AS no_of_products
FROM gold.dim_products
GROUP BY product_line
ORDER BY no_of_products DESC;

-- Count products within each category.
SELECT
    category,
    COUNT(DISTINCT product_key) AS no_of_products
FROM gold.dim_products
GROUP BY category
ORDER BY no_of_products DESC;


-- =============================================================================
-- 6. Geographic Sales Performance
-- =============================================================================

-- Analyze sales revenue, quantity, and average recorded price by country.
SELECT
    c.country,
    SUM(s.sales_amount) AS total_sales,
    SUM(s.quantity) AS total_quantity,
    ROUND(AVG(s.price), 2) AS avg_price
FROM gold.fact_sales AS s
LEFT JOIN gold.dim_customers AS c
    ON s.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_sales DESC, total_quantity DESC, avg_price DESC;
